import Foundation

/// 클립보드 기록 하나.
public struct ClipboardItem: Codable, Sendable, Equatable, Identifiable {
    public enum Content: Codable, Sendable, Equatable {
        case text(String)
        /// 기록 폴더에 저장한 PNG 파일 이름
        case image(String)
        /// 파일 경로들
        case files([String])
    }

    public let id: UUID
    public var content: Content
    public var date: Date
    public var isPinned: Bool
    /// 복사한 앱(번들 ID)
    public var sourceApp: String?

    public init(id: UUID = UUID(), content: Content, date: Date = .now, isPinned: Bool = false, sourceApp: String? = nil) {
        self.id = id
        self.content = content
        self.date = date
        self.isPinned = isPinned
        self.sourceApp = sourceApp
    }

    /// 파일로 저장된 스크린샷을 기록에 넣을 때 쓰는 출처(macOS 스크린샷 앱)
    public static let screenshotSource = "com.apple.screenshot.launcher"

    /// 목록에 보일 한 줄
    public var summary: String {
        switch content {
        case .text(let text):
            // 비어 있지 않은 첫 줄
            return text.split(whereSeparator: \.isNewline)
                .map { $0.trimmingCharacters(in: .whitespaces) }
                .first { !$0.isEmpty } ?? ""
        case .image: return sourceApp == Self.screenshotSource ? "스크린샷" : "이미지"
        case .files(let paths):
            let names = paths.map { ($0 as NSString).lastPathComponent }
            return names.count == 1 ? names[0] : "\(names[0]) 외 \(names.count - 1)개"
        }
    }

    /// 검색에 쓰는 글
    var searchText: String {
        switch content {
        case .text(let text): text
        case .image: sourceApp == Self.screenshotSource ? "스크린샷 이미지" : "이미지"
        case .files(let paths): paths.joined(separator: " ")
        }
    }
}

/// 기록 규칙(디스크와 떨어진 순수한 부분이라 테스트한다).
public enum ClipboardRules {
    /// 비밀번호 관리자 등이 "기록하지 말라"고 표시한 형식(nspasteboard.org 약속)
    public static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    public static func shouldSkip(types: [String]) -> Bool {
        !skippedTypes.isDisjoint(with: types)
    }

    /// 새 항목을 맨 앞에 넣는다. 같은 글·같은 파일은 하나만 남기고(고정 여부는 이어받음),
    /// 고정하지 않은 항목이 `limit`개를 넘으면 오래된 것부터 뺀다. 빠진 항목도 돌려준다(이미지 파일 정리용).
    public static func adding(_ item: ClipboardItem, to items: [ClipboardItem], limit: Int) -> (items: [ClipboardItem], removed: [ClipboardItem]) {
        var new = item
        var result = items
        if let duplicate = result.first(where: { $0.content == item.content }) {
            new.isPinned = duplicate.isPinned
            result.removeAll { $0.id == duplicate.id }
        }
        result.insert(new, at: 0)
        var removed: [ClipboardItem] = []
        var unpinned = 0
        result = result.filter { entry in
            if entry.isPinned { return true }
            unpinned += 1
            if unpinned > limit {
                removed.append(entry)
                return false
            }
            return true
        }
        return (result, removed)
    }

    /// 고정한 것을 먼저, 그다음 최신 순. 검색어가 있으면 글에 들어 있는 것만.
    public static func filtered(_ items: [ClipboardItem], query: String) -> [ClipboardItem] {
        let matched = query.isEmpty ? items : items.filter { $0.searchText.localizedCaseInsensitiveContains(query) }
        return matched.filter(\.isPinned) + matched.filter { !$0.isPinned }
    }
}

/// 기록을 이 맥(~/Library/Application Support/Mactatus/Clipboard)에만 저장한다.
struct ClipboardDisk {
    let folder: URL

    init(folder: URL = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        .appendingPathComponent("Mactatus/Clipboard")) {
        self.folder = folder
    }

    private var listURL: URL { folder.appendingPathComponent("history.json") }
    var imagesFolder: URL { folder.appendingPathComponent("Images") }

    func load() -> [ClipboardItem] {
        guard let data = try? Data(contentsOf: listURL) else { return [] }
        return (try? JSONDecoder().decode([ClipboardItem].self, from: data)) ?? []
    }

    func save(_ items: [ClipboardItem]) {
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try? JSONEncoder().encode(items).write(to: listURL, options: [.atomic, .completeFileProtection])
    }

    func saveImage(_ png: Data) -> String? {
        let name = UUID().uuidString + ".png"
        do {
            try FileManager.default.createDirectory(at: imagesFolder, withIntermediateDirectories: true)
            try png.write(to: imagesFolder.appendingPathComponent(name), options: .atomic)
            return name
        } catch {
            return nil
        }
    }

    func imageURL(_ name: String) -> URL { imagesFolder.appendingPathComponent(name) }

    func discard(_ items: [ClipboardItem]) {
        for item in items {
            if case .image(let name) = item.content { try? FileManager.default.removeItem(at: imageURL(name)) }
        }
    }
}
